function lang() {
  const l = Settings.get("lang");
  if (l) return l;
  const nav = (navigator.language || "ar").slice(0, 2);
  return ["ar", "fr", "en"].includes(nav) ? nav : "ar";
}

function t(key, vars) {
  let s = (STRINGS[lang()] || STRINGS.ar)[key];
  if (s == null) s = STRINGS.ar[key] != null ? STRINGS.ar[key] : key;
  if (vars) Object.entries(vars).forEach(([k, v]) => { s = s.split(`{${k}}`).join(v); });
  return s;
}

function applyLang() {
  const l = lang();
  document.documentElement.lang = l;
  document.documentElement.dir = l === "ar" ? "rtl" : "ltr";
}

function setLang(l) {
  Settings.set("lang", l);
  applyLang();
}

function langLabel() { return { ar: "ع", fr: "FR", en: "EN" }[lang()]; }

function cycleLang() {
  const order = ["ar", "fr", "en"];
  setLang(order[(order.indexOf(lang()) + 1) % 3]);
  Sfx.click();
  route();
  toast({ ar: "العربية", fr: "Français", en: "English" }[lang()]);
}
